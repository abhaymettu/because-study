"""Applies the pool rule to the pilots and writes the disposition of every candidate rule to docs/POOL.md."""

import json
from pathlib import Path

from study1.design import bare_rule
from study1.rules import ALL_RULES, POOL_FINAL, score
from study1.trace import Trace

# one_blank was reworded after pilot 2, so only pilot 3 speaks for it.
PILOTS = ("data/pilot1", "data/p2sonnet", "data/p3")
SEPARATE = {"data/p2sonnet": {"one_blank"}, "data/pilot1": {"no_markdown_final", "one_blank", "no_from_imports", "lint_before_commit"}}
LOW, HIGH, BASE_MAX = 0.10, 0.95, 0.50
# A stricter version of the same behavior; showing both would measure one rule twice.
SUPERSEDED = {"line_length": "line_60"}


def tally():
    shown, base = {}, {}
    pools = {p: _pool(p) for p in PILOTS}
    for pilot in PILOTS:
        skip = SEPARATE.get(pilot, set())
        for line in Path(pilot, "manifest.jsonl").read_text().splitlines():
            row = json.loads(line)
            doc = json.loads(Path(pilot, "traces", f"{row['run_id']}.json").read_text())
            s = score(Trace.from_json(doc["trace"]))
            targets = {t["rule"] for t in row["targets"]}
            for r in ALL_RULES:
                if r.id in skip:
                    continue
                if r.id in targets:
                    shown.setdefault(r.id, []).append(s[r.id])
                elif r.id != row["control_rule"] and r.id in pools[pilot]:
                    base.setdefault(r.id, []).append(s[r.id])
    return shown, base


def _pool(pilot):
    rows = [json.loads(l) for l in Path(pilot, "manifest.jsonl").read_text().splitlines()]
    return {t["rule"] for row in rows for t in row["targets"]}


def main():
    shown, base = tally()
    mean = lambda x: sum(x) / len(x) if x else None
    rows, chosen = [], []
    for r in ALL_RULES:
        s, b = mean(shown.get(r.id, [])), mean(base.get(r.id, []))
        if s is None:
            status = "not piloted"
        elif r.id in SUPERSEDED:
            status = f"dropped: superseded by {SUPERSEDED[r.id]}"
        elif s > HIGH:
            status = "dropped: ceiling"
        elif s < LOW:
            status = "dropped: floor"
        elif b is not None and b > BASE_MAX:
            status = "dropped: default behavior"
        else:
            status = "kept"
            chosen.append(r.id)
        rows.append((r, s, len(shown.get(r.id, [])), b, status))
    assert set(chosen) == set(POOL_FINAL), set(chosen) ^ set(POOL_FINAL)
    lines = [
        "# Rule pool and dispositions", "",
        f"Generated by `analysis/pool_table.py` from pilots 1, 2 and 3 (Sonnet 5.5, medium effort). Pool rule: shown compliance in [{LOW}, {HIGH}], no-rule compliance at or below {BASE_MAX}.",
        "", f"{len(chosen)} of {len(rows)} candidates kept.", "",
        "| Rule | Cost class | Shown | n | No rule | Disposition | Bare wording |", "|---|---|---|---|---|---|---|",
    ]
    fmt = lambda v: "" if v is None else f"{v:.2f}"
    for r, s, n, b, status in sorted(rows, key=lambda x: (x[4] != "kept", x[1] if x[1] is not None else 2)):
        lines.append(f"| `{r.id}` | {r.cost} | {fmt(s)} | {n} | {fmt(b)} | {status} | {bare_rule(r)} |")
    Path("docs/POOL.md").write_text("\n".join(lines) + "\n")
    print(len(chosen), "kept of", len(rows))
    for r, s, n, b, status in rows:
        if status == "kept":
            print(f"{r.id:24}{s:.2f} {n:4} {b if b is None else round(b, 2)}")


if __name__ == "__main__":
    main()
